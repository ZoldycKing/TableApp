/**
 * Решения — вторая ось сайта.
 *
 * Человек приходит либо с задачей («учёт заявок»), либо с собой («я из
 * сервиса»). Обе дороги ведут на одну страницу решения, устроенную
 * одинаково: что болит, что появится вместо этого, как идёт работа,
 * что видно на экране, чего пока нет.
 *
 * Правило: на странице нет ничего, чего продукт не делает сегодня. У решения,
 * за которым стоит шаблон, кнопка ставит его одним нажатием; там, где шаблона
 * нет, так и написано.
 *
 * Прежде эти страницы жили на `/dlya/*` и назывались сценариями. Переехали
 * они не ради слова: адрес `/solutions/production` читается и в ссылке,
 * и в отчёте поиска, а старые адреса переведены постоянным редиректом.
 */

export type SolutionStep = {
  /** Кто действует: «Начальник производства», «TableApp», «Клиент». */
  actor: string
  text: string
}

export type Solution = {
  slug: string
  emoji: string
  /** Короткое название — для карточек и навигации. */
  name: string
  short: string
  h1: string
  /** Заголовок для поиска: то же дело словами человека, который его ищет. */
  seoTitle: string
  /** Описание для выдачи. Одно предложение, своё у каждой страницы. */
  description: string
  lead: string
  who: string
  /** Как это устроено сейчас, до нас. */
  pains: string[]
  /** Четыре вещи, которые появляются. */
  blocks: { title: string; text: string }[]
  /** Как идёт работа: кто что делает по шагам. */
  workflow: SolutionStep[]
  /** Что видно на экране — конкретика вместо обещаний. */
  example: { title: string; lines: string[] }
  /** Шаблон, который разворачивает решение одним нажатием. */
  templateId: string | null
  /** Частые вопросы именно по этому делу. */
  faq: { question: string; answer: string }[]
  /** Чего в этом решении пока нет: лучше сказать заранее. */
  limits: string[]
  /** Соседние решения: человек редко приходит ровно за одним. */
  related: string[]
  industries: string[]
}

