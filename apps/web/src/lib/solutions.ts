export function findSolution(slug: string): Solution | undefined {
  return SOLUTIONS.find(item => item.slug === slug)
}

/** Keep each solution's next step specific, including capabilities without a template. */
export function solutionEntry(solution: Solution): { href: string; label: string } {
  if (solution.templateId) return { href: `/templates/${solution.templateId}`, label: 'Открыть шаблон' }
  if (solution.slug === 'client-portal') return { href: '/templates?preview=zakazy', label: 'Выбрать шаблон' }
  return { href: '/import', label: 'Создать из своей таблицы' }
}

