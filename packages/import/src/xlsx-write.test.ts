import { beforeAll, describe, expect, it } from 'vitest'
import { readSheets } from './xlsx'
import { sheetName, writeXlsx } from './xlsx-write'

/*
 * Прогрев библиотеки до тестов.
 *
 * Первый разбор книги тянет за собой `exceljs` — на свободной машине это
 * около четырёхсот миллисекунд, под нагрузкой заметно больше. Без прогрева
 * эту цену платит первый тест файла: он один шёл 441 мс при 1–23 мс
 * у остальных, и именно он упирался в предел в пять секунд, когда рядом
 * шла сборка. Предел не поднимаем — убираем из теста чужую работу.
 */
beforeAll(async () => {
  await import('exceljs')
}, 30_000)


/**
 * Запись книги проверяется чтением: файл, который мы отдаём человеку, должен
 * открываться — и открываться с теми же значениями. Проверять байты нечем,
 * а прочитать своим же разборщиком можно, и это единственная проверка,
 * которая что-то доказывает.
 */

describe('имя листа', () => {
  it('знаки, которых Excel не принимает, заменяются', () => {
    // С ними книга не открывается вовсе — не «выглядит плохо», а не открывается.
    expect(sheetName('Заявки/2026: [первый]')).toBe('Заявки 2026 первый')
  })

  it('длинное имя обрезается до предела Excel', () => {
    expect(sheetName('я'.repeat(50))).toHaveLength(31)
  })

  it('от пустого имени остаётся запасное', () => {
    expect(sheetName('  ***  ')).toBe('Лист 1')
    expect(sheetName('')).toBe('Лист 1')
  })
})

describe('книга', () => {
  it('открывается и содержит то, что записали', async () => {
    const bytes = await writeXlsx({
      name: 'Заявки',
      header: ['Клиент', 'Сумма'],
      rows: [
        ['ООО «Ромашка»', '1 250 000,5'],
        ['ИП Иванов', '187 400'],
      ],
    })

    const [read] = await readSheets(bytes)
    expect(read!.name).toBe('Заявки')
    expect(read!.grid[0]).toEqual(['Клиент', 'Сумма'])
    expect(read!.grid[1]).toEqual(['ООО «Ромашка»', '1 250 000,5'])
    expect(read!.grid[2]).toEqual(['ИП Иванов', '187 400'])
  })

  it('это настоящий xlsx, а не что-то похожее', async () => {
    // Книга — это zip: первые два байта «PK». Заголовок ответа обещает
    // именно её, и отдать под ним другое значит сломать открытие файла.
    const bytes = await writeXlsx({ name: 'Л', header: ['А'], rows: [] })
    expect(bytes[0]).toBe(0x50)
    expect(bytes[1]).toBe(0x4b)
  })

  it('пустая таблица даёт книгу с одной шапкой, а не ошибку', async () => {
    /*
     * Выгрузить пустой список человек может запросто — например, отобрав
     * статус, под который ничего не подходит. Файл с одной шапкой честно
     * отвечает «здесь ничего нет»; ошибка заставила бы гадать, что сломалось.
     */
    const bytes = await writeXlsx({ name: 'Пусто', header: ['Клиент'], rows: [] })
    const [read] = await readSheets(bytes)
    expect(read!.info.header).toEqual(['Клиент'])
    // Строк данных в таком листе нет, и обратно импорт его не возьмёт:
    // таблица из одних заголовков — это случайно созданная пустая таблица.
    expect(read!.info.rows).toBe(0)
    expect(read!.info.blockers).toEqual([{ kind: 'empty' }])
  })

  it('таблица без колонок не роняет запись', async () => {
    const bytes = await writeXlsx({ name: 'Ничего', header: [], rows: [] })
    expect(bytes.byteLength).toBeGreaterThan(0)
  })

  it('длинные значения не растягивают колонку без предела', async () => {
    // Иначе одно примечание уводит таблицу за край экрана.
    const bytes = await writeXlsx({
      name: 'Длинно',
      header: ['Примечание'],
      rows: [['я'.repeat(500)]],
    })
    const [read] = await readSheets(bytes)
    expect(read!.grid[1]?.[0]).toHaveLength(500)
  })
})
