/**
 * Адрес сайта.
 *
 * Отдельным модулем от карты ссылок (`lib/site.ts`) — и это не вкусовщина,
 * а исправление отказа. Раньше `SITE_URL` жил там же, где списки разделов,
 * а списки нужны шапке и подвалу, то есть клиенту. В рабочей сборке
 * переменные окружения в браузер не попадают: до клиента доезжало пустое
 * значение, проверка ниже срабатывала **в браузере** и роняла весь скрипт
 * страницы на старте. Разметка приходила с сервера и выглядела целой,
 * а меню, выпадающие списки и переходы без перезагрузки не работали.
 * Поэтому адрес читается только там, где он действительно нужен:
 * в разметке, карте сайта и `robots.txt` — всё это считает сервер.
 *
 * **Не импортировать из файлов с `'use client'`.** За этим следит проверка
 * в `site.test.ts`: она читает исходники и падает, если такой импорт появится.
 *
 * `SITE_URL` — публичный домен, `APP_URL` — тот же домен в разработке.
 *
 * В рабочей сборке адрес **обязателен**, и подставить вместо него что-нибудь
 * разумное нельзя: канонический адрес с `localhost` поисковик прочитает
 * буквально и выбросит страницу из выдачи, а подставленный по умолчанию
 * чужой домен — это ссылки на чужой сайт в карте собственного. Поэтому
 * сборка с localhost в адресе падает здесь, а не всплывает через месяц
 * в поисковой консоли.
 */
function resolveSiteUrl(): string {
  const raw = (process.env.SITE_URL ?? process.env.APP_URL ?? '').trim().replace(/\/$/, '')
  const local = /^https?:\/\/(localhost|127\.0\.0\.1|\[::1\])(:\d+)?$/i.test(raw)

  if (process.env.NODE_ENV === 'production' && (raw === '' || local)) {
    throw new Error(
      'SITE_URL обязателен в рабочей сборке и не может указывать на localhost: ' +
        'по нему строятся канонические ссылки, карта сайта и robots.txt.',
    )
  }

  return raw || 'http://localhost:3000'
}

export const SITE_URL = resolveSiteUrl()

/** Абсолютный адрес страницы — для canonical, OpenGraph и карты сайта. */
export function absolute(path: string): string {
  return path === '/' ? `${SITE_URL}/` : `${SITE_URL}${path}`
}

/** Только имя домена: его ждёт директива `Host` в `robots.txt`. */
export function siteHost(): string {
  return new URL(SITE_URL).host
}
