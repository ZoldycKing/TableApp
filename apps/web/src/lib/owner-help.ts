export function helpForPath(path: string): string[] {
  if (path.startsWith('/templates')) return ['template', 'start']
  if (path.startsWith('/setup')) return ['template', 'schedule', 'publish']
  if (path.startsWith('/t/')) return ['tables', 'views', 'relations']
  if (path.startsWith('/tables')) return ['tables', 'relations', 'import']
  if (path.startsWith('/apps')) return ['publish', 'access']
  if (path.startsWith('/team')) return ['access']
  if (path.startsWith('/import')) return ['import', 'tables']
  if (path.startsWith('/messages')) return ['messages', 'access']
  return ['start', 'template', 'import']
}
