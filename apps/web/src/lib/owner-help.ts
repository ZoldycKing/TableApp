/** Contextual help must return to the app the owner is actually preparing. */
export function ownerHelpAppId(pathname: string, setupAppId: string | null): string | undefined {
  if (pathname === '/setup') return setupAppId || undefined
  const segment = /^\/apps\/([^/]+)$/.exec(pathname)?.[1]
  if (!segment) return undefined
  try { return decodeURIComponent(segment) } catch { return undefined }
}

export function ownerHelpAction(article: HelpArticle, appId?: string): { href: string; label: string } {
  if (article.id === 'company') return { href: `/setup?step=business${appId ? `&app=${encodeURIComponent(appId)}` : ''}`, label: article.label }
  if (article.id === 'schedule') return appId
    ? { href: `/setup?step=work&app=${encodeURIComponent(appId)}`, label: article.label }
    : { href: '/apps', label: 'Выбрать приложение' }
  if (article.id === 'start' && appId) return { href: `/setup?app=${encodeURIComponent(appId)}`, label: article.label }
  return { href: article.href, label: article.label }
}
