/**
 * Боковая панель: что выбирает человек и как она при этом выглядит.
 *
 * Панель всегда на экране и всегда **вне потока страницы**: узкая полоска
 * слева, которая разворачивается поверх содержимого. Раскладка при этом
 * не пересчитывается никогда — ни при наведении, ни при закреплении.
 *
 * Это главное правило. Прежде развёрнутая панель занимала колонку в 232
 * пикселя, и её открытие двигало всё справа: таблицу на тысячу строк,
 * конструктор приложений, сводку. Двести миллисекунд пересчёта раскладки
 * на каждое движение мышью к краю экрана — это дёрганье, которое видно.
 *
 * Состояний, которые человек выбирает, ровно два, и оба лежат в куке:
 *
 * - `auto` — полоска, разворачивается по наведению и схлопывается обратно;
 * - `pinned` — развёрнута постоянно, но по-прежнему поверх содержимого.
 *
 * Временный показ состоянием не является и не запоминается: это подсказка,
 * а не выбор. Запомни его — и панель переоткрылась бы человеку, который
 * её только что убрал.
 */

/**
 * Где хранится выбор человека.
 *
 * Имя лежит здесь, а не рядом с самой панелью, и это не вкусовщина: панель —
 * клиентский модуль, а Next подменяет **все** его экспорты клиентскими
 * ссылками. Серверная обёртка получила бы вместо строки объект и не нашла бы
 * куку вообще — молча, без ошибки, просто панель каждый раз забывала бы выбор.
 */
export const SIDEBAR_COOKIE = 'tableapp_sidebar'

/** Что выбрал человек. */
export type SidebarMode = 'auto' | 'pinned'

/** Как нарисована панель прямо сейчас: полоска или полная ширина. */
export type ShellVariant = 'rail' | 'wide'

/**
 * Значение куки, которое пишем впредь.
 *
 * Словом, а не единицей: куку читают глазами в отладчике, и `pinned` говорит
 * там больше, чем `0`.
 */
export const COOKIE_VALUE: Record<SidebarMode, string> = { auto: 'auto', pinned: 'pinned' }

/**
 * Разбор куки. Старые значения читаются дальше.
 *
 * Прежде кука хранила «свёрнуто ли»: `0` — развёрнута, `1` — свёрнута.
 * Развёрнутая становится закреплённой — человек её такой и оставил.
 * Всё остальное, включая незнакомое значение, — умолчание: полоска.
 */
export function modeFromCookie(value: string | undefined): SidebarMode {
  return value === 'pinned' || value === 'wide' || value === '0' ? 'pinned' : 'auto'
}

