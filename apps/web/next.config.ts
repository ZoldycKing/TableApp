import { existsSync } from 'node:fs'
import { resolve } from 'node:path'
import type { NextConfig } from 'next'
import { LEGACY_REDIRECTS } from './src/lib/site'

// Переменные окружения живут в одном .env в корне монорепозитория,
// чтобы скрипты и приложение не расходились в настройках подключения.
const rootEnv = resolve(import.meta.dirname, '../../.env')
if (existsSync(rootEnv)) process.loadEnvFile(rootEnv)

const config: NextConfig = {
  // Пакеты монорепозитория поставляются исходниками на TypeScript.
  transpilePackages: ['@tableapp/schema', '@tableapp/formula', '@tableapp/import', '@tableapp/db'],
  // Типизированные маршруты требуют полной пересборки на каждый новый путь,
  // а сборка рядом с дев-сервером портит .next. Польза не покрывает трение.
  typedRoutes: false,

  /**
   * Сколько весит тело запроса к серверному действию.
   *
   * По умолчанию у Next это один мегабайт, и импорт от этого ломался молча:
   * книга Excel на две-три тысячи строк весит больше, запрос обрывался
   * на уровне транспорта, и человек видел форму загрузки без единого слова
   * о том, что произошло. Интерфейс при этом обещал пятнадцать мегабайт.
   *
   * Двадцать четыре — это пятнадцать мегабайт книги плюс запас: разобранные
   * строки уходят на запись вторым запросом и в JSON занимают больше, чем
   * сам файл. Предел самого файла остаётся в коде импорта и проверяется
   * и в браузере, и на сервере.
   */
  experimental: {
    serverActions: { bodySizeLimit: '24mb' },
  },

  /**
   * Переезд старых адресов.
   *
   * Постоянный (308), а не временный: страницы переехали навсегда, и поисковик
   * должен перенести на новый адрес всё, что накопил за старым. Делается
   * на сервере, а не в браузере — редирект, написанный скриптом на странице,
   * поисковик читает как обычную страницу-дубль.
   *
   * Список один на весь проект: он же проверяется тестом и используется
   * в тексте страницы «404», чтобы человек понял, куда всё делось.
   */
  async redirects() {
    return LEGACY_REDIRECTS.map((rule) => ({
      source: rule.from,
      destination: rule.to,
      permanent: true,
    }))
  },
}

export default config
