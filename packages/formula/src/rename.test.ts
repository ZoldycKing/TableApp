import { describe, expect, it } from 'vitest'
import { referencesField, renameInExpression } from './rename'

describe('переименование поля в формуле', () => {
  it('переписывает ссылку', () => {
    expect(renameInExpression('{Остаток} <= {Минимум}', 'Остаток', 'Сколько лежит')).toBe(
      '{Сколько лежит} <= {Минимум}',
    )
  })

  it('переписывает все вхождения', () => {
    expect(renameInExpression('{Цена} * 2 + {Цена}', 'Цена', 'Стоимость')).toBe(
      '{Стоимость} * 2 + {Стоимость}',
    )
  })

  it('не трогает поля с похожими именами', () => {
    expect(renameInExpression('{Цена} + {Цена закупки}', 'Цена', 'Продажа')).toBe(
      '{Продажа} + {Цена закупки}',
    )
  })

  it('не трогает текст внутри строк', () => {
    // «Цена» здесь — слово в кавычках, а не ссылка на колонку.
    expect(renameInExpression('CONCAT("Цена: ", {Цена})', 'Цена', 'Стоимость')).toBe(
      'CONCAT("Цена: ", {Стоимость})',
    )
  })

  it('терпит пробелы вокруг имени', () => {
    expect(renameInExpression('{ Остаток } > 0', 'Остаток', 'Запас')).toBe('{Запас} > 0')
  })

  it('переименование в то же имя ничего не меняет', () => {
    expect(renameInExpression('{Цена} * 2', 'Цена', 'Цена')).toBe('{Цена} * 2')
  })

  it('видит, что формула смотрит на поле', () => {
    expect(referencesField('{Остаток} <= {Минимум}', 'Минимум')).toBe(true)
    expect(referencesField('{Остаток} <= {Минимум}', 'Цена')).toBe(false)
  })
})
