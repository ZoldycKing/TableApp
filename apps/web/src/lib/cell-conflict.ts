/**
 * Не затереть чужую правку молча.
 *
 * Таблицу правят вдвоём, и до сих пор побеждал тот, кто нажал позже:
 * его значение просто ложилось поверх, а первый узнавал об этом случайно
 * и не сразу. Теперь редактор присылает **то значение, которое видел перед
 * правкой**, и сервер сверяет его с тем, что лежит в базе. Разошлись —
 * значит, пока человек печатал, ячейку изменил кто-то другой, и его работу
 * мы не трогаем: правку отклоняем и показываем свежее значение.
 *
 * Это не блокировка строки и не история версий. Это ровно одно: «не записывай
 * поверх того, чего не видел». Строка в базе и так считает свои версии
 * (`rows.version`), но версия меняется от правки любого поля — сверять по ней
 * значило бы отклонять правку соседней колонки без всякой причины.
 */

/**
 * Одинаковые ли значения ячейки.
 *
 * Пустое и отсутствующее — одно и то же: колонка, которой не касались,
 * и колонка, которую очистили, для человека выглядят одинаково.
 * Остальное сравнивается по содержимому: в ячейке могут лежать массивы
 * вложений и выбранных значений, и порядок ключей в них не значим.
 */
export function sameCellValue(left: unknown, right: unknown): boolean {
  if (blank(left) && blank(right)) return true
  return canonical(left) === canonical(right)
}

function blank(value: unknown): boolean {
  return value === null || value === undefined || value === ''
}

function canonical(value: unknown): string {
  return JSON.stringify(sort(value))
}

/** Ключи объектов по алфавиту: порядок полей не делает значение другим. */
function sort(value: unknown): unknown {
  if (Array.isArray(value)) return value.map(sort)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.entries(value as Record<string, unknown>)
        .sort(([left], [right]) => left.localeCompare(right))
        .map(([key, item]) => [key, sort(item)]),
    )
  }
  return value
}

